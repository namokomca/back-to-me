import assert from 'node:assert/strict';
import {emptyProfile,questionSteps,questionError,finishProfile} from './src/onboarding.js';
let p=emptyProfile();
assert.ok(questionError('who',p));
assert.ok(questionError('birthday',{...p,birthday:'2099-01-01'}));
assert.ok(questionError('birthday',{...p,birthday:'2025-02-30'}));
p={...p,who:'배우자',partnerDate:'2026-11-30',childName:'콩콩',birthday:'2025-09-07',enrolled:false,mine:{...p.mine,mode:'자동차'},partner:{...p.partner,mode:'도보'}};
assert.ok(!questionSteps(p).includes('school'));
assert.ok(!questionSteps(p).includes('mineTravel'));
for(const id of questionSteps(p))assert.equal(questionError(id,p),'',id);
assert.equal(finishProfile(p).date,'2026-11-30');
assert.equal(finishProfile(p).homeMinutes,0);
p.enrolled=true;
assert.ok(questionSteps(p).includes('school'));
assert.ok(questionError('mineTravel',p),'blank minutes must not become zero');
assert.ok(questionError('mineWork',{...p,mine:{...p.mine,start:'18:00',end:'09:00'}}));
p.mine.outbound=0;p.mine.inbound=50;
assert.equal(questionError('mineTravel',p),'');
assert.equal(finishProfile(p).mine.inbound,50);
assert.equal(p.date,'','normalizing should not mutate the draft');
console.log('PASS questionnaire branching, date validation, unknown travel times, and normalization');
